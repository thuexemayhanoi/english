// Records the latest GitHub Actions runs (authenticated via GITHUB_TOKEN) so
// batch-26 gate/pages verification survives outside API rate limits.
const fs = require('fs');

const repo = process.env.GITHUB_REPOSITORY;
const token = process.env.GITHUB_TOKEN;

async function get(url) {
  const r = await fetch(url, {
    headers: {
      Authorization: 'Bearer ' + token,
      Accept: 'application/vnd.github+json',
      'X-GitHub-Api-Version': '2022-11-28',
      'User-Agent': 'batch-26-verification-recorder'
    }
  });
  if (!r.ok) throw new Error('GET ' + url + ' -> HTTP ' + r.status);
  return r.json();
}

(async () => {
  const runs = await get('https://api.github.com/repos/' + repo + '/actions/runs?per_page=30');
  const lines = [
    '# Batch 26 final verification record',
    '',
    'Auto-generated by scripts/record-batch-26-verification.js in the Docs Sync workflow.',
    'Recorded at: ' + new Date().toISOString() + ' (UTC)',
    'Default branch: main. Latest 30 workflow runs at record time:',
    '',
    '| Workflow | Run ID | Head SHA | Status | Conclusion | Updated (UTC) |',
    '|---|---|---|---|---|---|'
  ];
  for (const run of runs.workflow_runs) {
    lines.push('| ' + run.name + ' | ' + run.id + ' | ' + String(run.head_sha || '').slice(0, 7) + ' | ' + run.status + ' | ' + (run.conclusion || '') + ' | ' + (run.updated_at || '') + ' |');
  }
  lines.push('');
  lines.push('Total runs in window: ' + runs.total_count);
  fs.writeFileSync('docs/sync/batch-26-final-verification.md', lines.join(String.fromCharCode(10)) + String.fromCharCode(10));
  console.log('record-batch-26-verification: recorded ' + runs.workflow_runs.length + ' runs.');
})().catch(e => { console.error('record-batch-26-verification: ' + e.message); process.exit(1); });
